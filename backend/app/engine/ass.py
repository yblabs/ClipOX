"""
ASS (Advanced SubStation Alpha) subtitle generator.

Turns the frontend's style configuration into a ready-to-burn ``.ass`` file:

.. code-block:: json

    {"motion": "moving", "palette": "neon", "font": "Montserrat",
     "size": "medium", "placement": "bottom"}

* ``motion``  -> ``stationary`` (one line per segment) or ``moving``
                 (word-by-word bounce/highlight karaoke).
* ``palette`` -> preset colour schemes, already converted to ``&HBBGGRR``.
* ``font``    -> any font installed on the render host.
* ``size``    -> small / medium / large (relative to a 1080x1920 canvas).
* ``placement`` -> bottom / center / top.

The file uses ``PlayResX: 1080 / PlayResY: 1920`` so libass scales it straight
onto vertical shorts.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional

# ---------------------------------------------------------------------------
# Style presets
# ---------------------------------------------------------------------------
PALETTES: Dict[str, Dict[str, str]] = {
    #                primary        highlight      outline
    "classic": {"primary": "#FFFFFF", "highlight": "#FFE14D", "outline": "#000000"},
    "white":   {"primary": "#FFFFFF", "highlight": "#FFFFFF", "outline": "#000000"},
    "neon":    {"primary": "#F2FFFF", "highlight": "#00FFF7", "outline": "#062033"},
    "contrast": {"primary": "#FFFFFF", "highlight": "#FFE14D", "outline": "#000000"},
    "brand":   {"primary": "#FFFFFF", "highlight": "#2BF5A0", "outline": "#04070A"},
    "ocean":   {"primary": "#EAF6FF", "highlight": "#38BDF8", "outline": "#04070A"},
}

FONTS = ["Montserrat", "Impact", "Anton", "Poppins"]
SIZES = {"small": 56, "medium": 78, "large": 104}
PLACEMENTS = {"bottom": 300, "center": 960, "top": 330}   # y in a 1920 canvas

PLAY_W, PLAY_H = 1080, 1920


# ---------------------------------------------------------------------------
# Colour helpers (hex -> ASS &HAABBGGRR)
# ---------------------------------------------------------------------------
def hex_to_ass(hex_color: str, alpha: int = 0) -> str:
    h = hex_color.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{alpha:02X}{b.upper()}{g.upper()}{r.upper()}"


def ass_time(sec: float) -> str:
    """``H:MM:SS.cc`` (ASS uses centiseconds)."""
    sec = max(0.0, float(sec))
    h = int(sec // 3600)
    m = int((sec % 3600) // 60)
    s = sec % 60
    return f"{h}:{m:02d}:{s:05.2f}"


# ---------------------------------------------------------------------------
# Style block
# ---------------------------------------------------------------------------
def build_header(font: str, size_key: str, palette: str, outline: int = 6) -> str:
    pal = PALETTES.get(palette, PALETTES["classic"])
    px = SIZES.get(size_key, SIZES["medium"])
    primary = hex_to_ass(pal["primary"])
    highlight = hex_to_ass(pal["highlight"])
    outline_c = hex_to_ass(pal["outline"])
    back = hex_to_ass(pal["outline"], alpha=0x80)
    font_name = font if font in FONTS else FONTS[0]

    # Two styles: dim context line + bright animated active word.
    base_style = (
        f"Style: Base,{font_name},{px},{primary},{highlight},{outline_c},{back},"
        f"-1,0,0,0,100,100,0,0,1,{outline},2,5,40,40,60,1"
    )
    active_style = (
        f"Style: Active,{font_name},{px},{highlight},{highlight},{outline_c},{back},"
        f"-1,0,0,0,100,100,0,0,1,{outline},2,5,40,40,60,1"
    )
    return (
        "[Script Info]\n"
        "; Generated by WayinVideo Clip Maker\n"
        "ScriptType: v4.00+\n"
        f"PlayResX: {PLAY_W}\n"
        f"PlayResY: {PLAY_H}\n"
        "WrapStyle: 0\n"
        "ScaledBorderAndShadow: yes\n"
        "YCbCr Matrix: TV.709\n"
        "\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, "
        "ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, "
        "MarginL, MarginR, MarginV, Encoding\n"
        f"{base_style}\n"
        f"{active_style}\n"
        "\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )


def pos_tag(placement: str) -> str:
    y = PLACEMENTS.get(placement, PLACEMENTS["bottom"])
    return f"\\an5\\pos({PLAY_W // 2},{y})"


# ---------------------------------------------------------------------------
# Event generation
# ---------------------------------------------------------------------------
def _clean(word: str) -> str:
    return word.replace("{", "(").replace("}", ")").replace("\\", "")


def events_stationary(segments: List[Dict[str, Any]], placement: str) -> List[str]:
    """One dialogue line per transcript segment, fixed position."""
    lines: List[str] = []
    anchor = pos_tag(placement)
    for seg in segments:
        text = _clean(seg.get("text", "").strip())
        if not text:
            continue
        # keep each cue short enough to stay on one or two lines
        offset = 0.0
        seg_start, seg_end = float(seg["start"]), float(seg["end"])
        span_total = max(0.1, seg_end - seg_start)
        for i in range(0, len(text), 78):
            chunk = text[i : i + 78].strip()
            if not chunk:
                continue
            share = len(chunk) / max(1, len(text))
            start = seg_start + offset
            span = span_total * share
            offset += span
            lines.append(
                f"Dialogue: 0,{ass_time(start)},{ass_time(start + span)},Base,,0,0,0,,"
                f"{{{anchor}\\blur2}}{chunk}"
            )
    return lines


def events_moving(segments: List[Dict[str, Any]], placement: str) -> List[str]:
    """Word-by-word karaoke: dim context line + bouncy highlighted word."""
    lines: List[str] = []
    anchor = pos_tag(placement)
    for seg in segments:
        words = [w for w in seg.get("words", []) if w.get("w")]
        if not words:
            text = seg.get("text", "").strip()
            if text:
                lines.append(
                    f"Dialogue: 0,{ass_time(seg['start'])},{ass_time(seg['end'])},Base,,0,0,0,,"
                    f"{{{anchor}\\blur2}}{_clean(text)}"
                )
            continue

        context = " ".join(_clean(w["w"]) for w in words)
        seg_start, seg_end = float(seg["start"]), float(seg["end"])
        # context line visible for the whole segment
        lines.append(
            f"Dialogue: 1,{ass_time(seg_start)},{ass_time(seg_end)},Base,,0,0,0,,"
            f"{{{anchor}\\blur2\\alpha&H50&}}{context}"
        )
        # highlighted bouncing word
        for i, w in enumerate(words):
            start = float(w["s"])
            end = float(w["e"])
            if i + 1 < len(words):                # hold until the next word starts
                end = max(end, min(float(words[i + 1]["s"]), end + 0.6))
            end = min(max(end, start + 0.12), seg_end + 0.3)
            anim = (
                f"{{{anchor}\\blur2\\fscx118\\fscy118"
                f"\\t(0,110,\\fscx100\\fscy100\\blur0)}}"
            )
            lines.append(
                f"Dialogue: 2,{ass_time(start)},{ass_time(end)},Active,,0,0,0,,"
                f"{anim}{_clean(w['w'])}"
            )
    return lines


def generate_ass(
    segments: List[Dict[str, Any]],
    style: Dict[str, Any],
    out_path: Path | str,
) -> Path:
    """Write a complete ``.ass`` file for *segments* using *style*."""
    style = dict(style or {})
    motion = style.get("motion", "stationary")
    palette = style.get("palette", "classic")
    font = style.get("font", "Montserrat")
    size = style.get("size", "medium")
    placement = style.get("placement", "bottom")
    outline = int(style.get("outline", 5 if palette != "contrast" else 8))

    events = events_moving(segments, placement) if motion == "moving" else events_stationary(segments, placement)

    content = build_header(font, size, palette, outline) + "\n".join(events) + "\n"
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return out_path


def style_summary(style: Dict[str, Any]) -> str:
    """Human readable one-liner used in API responses / logs."""
    s = dict(style or {})
    return (
        f"{s.get('motion', 'stationary')} · {s.get('palette', 'classic')} · "
        f"{s.get('font', 'Montserrat')} · {s.get('size', 'medium')} · "
        f"{s.get('placement', 'bottom')}"
    )
